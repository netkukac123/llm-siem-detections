"""Render docs/coverage-matrix.md from the labels and the rule metadata.

    python -m simulate.coverage

The matrix only restates ground truth; the test suites are what prove that
both the KQL and the Wazuh rules actually behave this way.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULE_IDS = [f"LLMD-{i:03d}" for i in range(1, 13)]


def main() -> None:
    rules = {}
    for p in sorted((ROOT / "detections" / "sentinel").glob("LLMD-*.yaml")):
        r = yaml.safe_load(p.read_text(encoding="utf-8"))
        rules[r["name"][:8]] = r
    labels = json.loads((ROOT / "datasets" / "labels.json").read_text(encoding="utf-8"))

    out = ["# Coverage matrix", "",
           "Generated by `python -m simulate.coverage` from `datasets/labels.json`. "
           "`X` = must fire, `miss` = documented gap (asserted silent), blank = must stay silent. "
           "Both `tests/test_kql_rules.py` and `tests/test_wazuh_rules.py` enforce every cell.", "",
           "## Rules", "", "| Rule | Severity | OWASP LLM 2025 | MITRE ATLAS |", "|---|---|---|---|"]
    for rid in RULE_IDS:
        r = rules[rid]
        owasp = ", ".join(t.split(" ", 1)[0].removeprefix("OWASP-") for t in r["tags"] if t.startswith("OWASP"))
        atlas = ", ".join(t.split(" ")[1] for t in r["tags"] if t.startswith("ATLAS"))
        out.append(f"| **{rid}** {r['name'][9:]} | {r['severity']} | {owasp} | {atlas} |")

    short = [rid[-3:] for rid in RULE_IDS]
    out += ["", "## Scenarios", "", "| Scenario | Kind | " + " | ".join(short) + " |",
            "|---|---|" + "|".join([":-:"] * len(short)) + "|"]
    benign = [l for l in labels if l["kind"] == "benign" and not l["expect"] and l["scenario"].startswith("benign-") and l["scenario"][7:].isdigit()]
    for l in labels:
        if l in benign:
            continue
        cells = ["X" if rid in l["expect"] else "miss" if rid in l["known_miss"] else "" for rid in RULE_IDS]
        out.append(f"| `{l['scenario']}` | {l['kind']} | " + " | ".join(cells) + " |")
    out.append(f"| {len(benign)} ordinary benign sessions | benign | " + " | ".join([""] * len(short)) + " |")
    out += ["", "## Scenario notes", ""]
    for l in labels:
        if l not in benign:
            out.append(f"- `{l['scenario']}`: {l['description']}")
    (ROOT / "docs" / "coverage-matrix.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("docs/coverage-matrix.md written")


if __name__ == "__main__":
    main()
